"""The skills are the product's brain and ship in two places (Claude Code and GitHub Copilot).
These tests keep them valid, identical, and discoverable."""

import importlib.util
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("sync_skills", ROOT / "scripts" / "sync_skills.py")
sync = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sync)

CLAUDE = ROOT / ".claude" / "skills"
COPILOT = ROOT / ".github" / "skills"
EXPECTED = {
    "build-my-site", "setup-my-computer", "publish-to-github", "render-django", "site-ops",
    "building-an-app", "site-mentor", "privacy-advisor", "google-sign-in", "email-resend",
    "custom-domain", "openai-ai-features", "backups-and-restore", "cost-monitoring",
    "verify-my-site", "site-security", "data-model-coach", "design-review",
    "release-train",  # optional: only for several apps built at once by several AI sessions
}  # fmt: skip


def test_every_capability_has_a_skill():
    assert {p.name for p in CLAUDE.iterdir() if p.is_dir()} == EXPECTED


@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_skill_frontmatter_is_valid_for_both_tools(name):
    meta = sync.parse_frontmatter((CLAUDE / name / "SKILL.md").read_text(encoding="utf-8"))
    assert meta["name"] == name
    assert re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) and len(name) <= 64
    assert 40 <= len(meta["description"]) <= 1024  # Copilot's limit
    assert "TRIGGER:" in meta["description"], "a skill nobody can trigger is dead weight"


def test_the_copilot_copy_is_identical_to_the_claude_source():
    assert sync.drift() == [], "run: python scripts/sync_skills.py"


def test_every_source_file_is_mirrored_byte_for_byte():
    for src in CLAUDE.rglob("*"):
        if src.is_file():
            copy = COPILOT / src.relative_to(CLAUDE)
            assert copy.exists(), copy
            assert sync.normalise(copy.read_bytes()) == sync.normalise(src.read_bytes()), copy


def test_a_skill_edit_that_is_not_synced_is_caught(tmp_path, monkeypatch):
    """A guard that cannot be tripped is worthless: prove the drift check notices."""
    skill = CLAUDE / "design-review" / "SKILL.md"
    original = skill.read_bytes()
    try:
        skill.write_bytes(original + b"\nan unsynced edit\n")
        assert any("design-review" in problem for problem in sync.drift())
    finally:
        skill.write_bytes(original)
    assert sync.drift() == []


def test_instructions_files_index_every_skill():
    for target in sync.INSTRUCTION_FILES:
        text = target.read_text(encoding="utf-8")
        assert "GENERATED by scripts/sync_skills.py" in text
        for name in EXPECTED:
            assert f"`{name}`" in text, (target.name, name)
            assert f".github/skills/{name}/SKILL.md" in text


def test_instructions_keep_the_standing_rules():
    text = (ROOT / ".github" / "copilot-instructions.md").read_text(encoding="utf-8")
    for must in ("git push", "private", "env/", "advise"):
        assert must in text.lower() or must in text


def test_build_my_site_hands_over_to_every_other_skill():
    text = (CLAUDE / "build-my-site" / "SKILL.md").read_text(encoding="utf-8")
    for name in EXPECTED - {"build-my-site"}:
        assert f"`{name}`" in text, f"build-my-site never mentions {name}"


def test_the_github_copy_links_work_from_inside_dot_github():
    """Found by the link checker: links written for the repo root break one folder down."""
    inside = (ROOT / ".github" / "copilot-instructions.md").read_text(encoding="utf-8")
    at_root = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    assert "](../docs/" in inside and "](docs/" not in inside
    assert "](docs/" in at_root and "](../docs/" not in at_root


def test_crlf_line_endings_are_not_reported_as_drift(tmp_path, monkeypatch):
    """A Windows checkout may turn LF into CRLF. That is not a change to the skills."""
    skill = CLAUDE / "design-review" / "SKILL.md"
    copy = COPILOT / "design-review" / "SKILL.md"
    original = copy.read_bytes()
    try:
        copy.write_bytes(original.replace(b"\n", b"\r\n"))
        assert sync.drift() == []
    finally:
        copy.write_bytes(original)
    assert skill.exists()
